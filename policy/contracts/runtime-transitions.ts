export function assertTransition(from: string, to: string): void {
	if (
		!(RUNTIME_STATES as readonly string[]).includes(from) ||
		!(RUNTIME_STATES as readonly string[]).includes(to)
	) {
		throw new SdlcError('INVALID_TRANSITION', `Unknown transition ${from} -> ${to}`);
	}
	if (!ALLOWED_TRANSITIONS[from as RuntimeStateName].has(to as RuntimeStateName)) {
		throw new SdlcError('INVALID_TRANSITION', `Transition ${from} -> ${to} is not allowed`);
	}
}
